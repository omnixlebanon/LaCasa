CREATE INDEX ON product_items (item_id);
CREATE INDEX ON shifts (user_id, shift_date);
CREATE INDEX ON recurring_shifts (user_id, starts_on);
CREATE INDEX ON workflow_requests (status, created_at);
CREATE INDEX ON workflow_requests (user_id);
CREATE INDEX ON shift_checkins (user_id, checked_in_at);
CREATE INDEX ON shift_checkins (shift_id);
CREATE INDEX ON salary_deductions (user_id, deducted_at);
CREATE INDEX ON payroll_payment_events (user_id, salary_month);

-- Preserve the local database's expiration triggers (including refunds and bot receipts).
CREATE FUNCTION refresh_batch_expiration() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP <> 'INSERT' THEN
  UPDATE items SET "exDate" = (SELECT MIN("batch_exDate") FROM batches
   WHERE item_id = OLD.item_id AND batch_stock > 0) WHERE item_id = OLD.item_id;
 END IF;
 IF TG_OP <> 'DELETE' THEN
  UPDATE items SET "exDate" = (SELECT MIN("batch_exDate") FROM batches
   WHERE item_id = NEW.item_id AND batch_stock > 0) WHERE item_id = NEW.item_id;
 END IF;
 RETURN NULL;
END;
$$;
CREATE TRIGGER batch_expiration AFTER INSERT OR UPDATE OR DELETE ON batches
 FOR EACH ROW EXECUTE FUNCTION refresh_batch_expiration();

CREATE FUNCTION refresh_salary_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN NEW.updated_at = CURRENT_TIMESTAMP; RETURN NEW; END;
$$;
CREATE TRIGGER salary_updated_at BEFORE UPDATE ON employee_salary_rates
 FOR EACH ROW EXECUTE FUNCTION refresh_salary_updated_at();

-- Authentication stays in Express. No direct access from Supabase's browser Data API.
DO $$
DECLARE table_name text;
BEGIN
 FOREACH table_name IN ARRAY ARRAY['users','floors','tablez','item_categories','items','suppliers','batches',
 'product_categories','products','product_items','monthly_order_sequences','orders_history','recurring_shifts',
 'shifts','workflow_requests','shift_checkins','employee_salary_rates','salary_deductions',
 'employee_payroll_payments','payroll_payment_events'] LOOP
  EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', table_name);
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
   EXECUTE format('REVOKE ALL ON public.%I FROM anon', table_name);
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
   EXECUTE format('REVOKE ALL ON public.%I FROM authenticated', table_name);
  END IF;
 END LOOP;
END;
$$;

-- Business expenses
CREATE TABLE IF NOT EXISTS business_expenses (
  expense_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category VARCHAR(30) NOT NULL,
  description VARCHAR(200) NOT NULL,
  amount NUMERIC(12,2) NOT NULL CHECK (amount > 0),
  expense_date DATE NOT NULL,
  recorded_by INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_business_expense_date ON business_expenses(expense_date);
ALTER TABLE business_expenses ENABLE ROW LEVEL SECURITY;
DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN REVOKE ALL ON business_expenses FROM anon; END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN REVOKE ALL ON business_expenses FROM authenticated; END IF;
END $$;

CREATE TABLE IF NOT EXISTS expense_recurrences (
  expense_id BIGINT PRIMARY KEY REFERENCES business_expenses(expense_id) ON DELETE CASCADE,
  frequency VARCHAR(10) NOT NULL,
  repeat_until DATE NULL,
  stopped_before DATE NULL
);
ALTER TABLE expense_recurrences ENABLE ROW LEVEL SECURITY;
DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN REVOKE ALL ON expense_recurrences FROM anon; END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN REVOKE ALL ON expense_recurrences FROM authenticated; END IF;
END $$;
