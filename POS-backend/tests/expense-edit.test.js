const test = require('node:test');
const assert = require('node:assert/strict');
const express = require('express');
const { PGlite } = require('@electric-sql/pglite');
const { wrap } = require('../config/postgres');

test('repeating bills can be edited and deleted, and one-time rent can start repeating', async t => {
    const engine = new PGlite();
    await engine.exec(`CREATE TABLE business_expenses(expense_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,category text,description text,amount numeric,expense_date date,recorded_by integer);
        CREATE TABLE expense_recurrences(expense_id integer PRIMARY KEY REFERENCES business_expenses ON DELETE CASCADE,frequency text,repeat_until date,stopped_before date);`);
    const connection = wrap({ async query(config) {
        const result = await engine.query(config.text, config.values);
        return { ...result, rows: result.rows.map(row => Object.fromEntries(Object.entries(row).map(([key, value]) => [key, value instanceof Date ? value.toISOString().slice(0, 10) : value]))), rowCount: result.affectedRows ?? result.rows.length };
    } });
    const db = { ...connection, getConnection: async () => ({ ...connection, beginTransaction: () => engine.exec('BEGIN'), commit: () => engine.exec('COMMIT'), rollback: () => engine.exec('ROLLBACK'), release() {} }) };
    const path = require.resolve('../config/database');
    require.cache[path] = { id: path, filename: path, loaded: true, exports: db };
    const app = express(); app.use(express.json());
    app.use((req, res, next) => { req.user = { user_id: 1, access_level: 'admin' }; next(); });
    app.use('/api', require('../routes/expenseRout'));
    const server = app.listen(0, '127.0.0.1');
    await new Promise(resolve => server.once('listening', resolve));
    t.after(async () => { server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); await engine.close(); });
    const url = `http://127.0.0.1:${server.address().port}/api/expenses`;
    const write = (suffix, method, data) => fetch(url + suffix, { method, headers: { 'Content-Type': 'application/json' }, body: data && JSON.stringify(data) });
    const bill = { category: 'internet', description: 'Internet', amount: '12.00', date: '2026-01-31', frequency: 'monthly' };
    const created = await write('', 'POST', bill); assert.equal(created.status, 201);
    const { id } = await created.json();
    assert.equal((await write(`/${id}`, 'PATCH', { ...bill, amount: '15.00', repeat_until: '2026-03-31' })).status, 200);
    let rows = await (await fetch(url + '?month=2026-02')).json();
    assert.equal(rows[0].start_date, '2026-01-31'); assert.equal(rows[0].expense_date, '2026-02-28'); assert.equal(Number(rows[0].amount), 15);
    assert.equal((await write(`/${id}`, 'PATCH', { ...bill, amount: '20.00', frequency: 'invalid' })).status, 400);
    rows = await (await fetch(url + '?month=2026-02')).json(); assert.equal(Number(rows[0].amount), 15);
    assert.equal((await write(`/${id}`, 'DELETE')).status, 200);
    assert.deepEqual(await (await fetch(url + '?month=2026-02')).json(), []);
    const rent = { ...bill, category: 'rent', description: 'Rent', frequency: 'none' };
    const rentId = (await (await write('', 'POST', rent)).json()).id;
    assert.equal((await write(`/${rentId}`, 'PATCH', { ...rent, frequency: 'monthly' })).status, 200);
    rows = await (await fetch(url + '?month=2026-02')).json(); assert.equal(rows[0].recurring, true);
    assert.equal((await write(`/${rentId}`, 'PATCH', rent)).status, 200);
    assert.deepEqual(await (await fetch(url + '?month=2026-02')).json(), []);
});
